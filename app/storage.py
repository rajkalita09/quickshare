"""Safe on-disk storage for uploaded files."""

from __future__ import annotations

from pathlib import Path
from uuid import uuid4

from werkzeug.datastructures import FileStorage
from werkzeug.utils import secure_filename


def ensure_upload_dir(upload_dir: Path) -> None:
    upload_dir.mkdir(parents=True, exist_ok=True)


def new_stored_name() -> str:
    # Internal names are random UUIDs so original filenames never become paths.
    return str(uuid4())


def sanitize_download_name(original_name: str | None) -> str:
    name = secure_filename(original_name or "")
    return name or "download"


def stored_path(upload_dir: Path, stored_name: str) -> Path:
    # stored_name is generated by the server, never taken from user input.
    return upload_dir / stored_name


def save_upload(upload_dir: Path, file_storage: FileStorage) -> tuple[str, int]:
    ensure_upload_dir(upload_dir)
    stored_name = new_stored_name()
    destination = stored_path(upload_dir, stored_name)
    file_storage.save(destination)
    size = destination.stat().st_size
    return stored_name, size


def delete_file(upload_dir: Path, stored_name: str) -> None:
    path = stored_path(upload_dir, stored_name)
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass
